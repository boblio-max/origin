"""Dialect table: maps foreign source lines to real Origin source.

Primary source of truth is ``origin.toml``, where each line
declares one mapping::

    "<origin source it maps to>" _ "<dialect source line>"

(left = the compilable Origin code, right = the line the user actually
writes). The parser replaces matching lines with a DialectNode placeholder
and the compiler expands the origin source inline (scalable: any number of
mappings, no precompilation step).

Mappings may be exact or templated. A ``$name`` in a mapping is a capture:

    "let x:int = 5" _ "x:5"          # exact: only the line "x:5"
    "let $n:int = $v" _ "$n:$v"      # template: x:5, y:10, count:42, ...

Template captures are substituted back into the left (origin) side, so the
concrete Origin source is compiled inline exactly like an exact mapping.
``$$`` escapes a literal dollar sign. Every ``$name`` on the left must also
appear on the right, otherwise the mapping is ignored.

``origin_bytecode.toml`` (generated by ``runner.py``)
is optionally loaded as a legacy/precompiled fallback: keys are dialect source
lines, values are a bytecode list or a ``{bytecode, constants}`` dict. Both
real TOML and the historical Python-dict repr are accepted. Because templated
mappings have unbounded variants they cannot be precompiled, so only exact
mappings ever appear there.
"""
import ast
import os
import re

_TABLE = None
_TABLE_PATH = None
_ORIGIN_MAP = None
_ORIGIN_MAP_PATH = None
_PATTERNS = None
_PATTERNS_PATH = None

# Matching is disabled while the compiler expands a mapped origin source,
# otherwise a broad template (e.g. "$n:$v") would re-match the substituted
# concrete source (e.g. "let x:int = 5") and expand forever.
_ENABLED = True

_WS_RUN = re.compile(r"\s+")
_PLACEHOLDER = re.compile(r"\$([A-Za-z_]\w*)")
_TEMPLATE_TOKEN = re.compile(r"\$\$|\$([A-Za-z_]\w*)")


def normalize_line(line):
    """Normalize a source line for key matching: strip quotes/space, single-space."""
    s = (line or "").strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in ("'", '"'):
        s = s[1:-1]
    s = s.strip().strip('"').strip("'").strip()
    return _WS_RUN.sub(" ", s)


def enabled():
    """Whether dialect matching is currently active."""
    return _ENABLED


def set_enabled(value):
    """Enable/disable dialect matching (used around inline expansion)."""
    global _ENABLED
    _ENABLED = bool(value)


def _default_path(name):
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), name)


def _parse_origin_toml(path):
    """Parse origin.toml into ordered [(origin_source, normalized_dialect)]."""
    if not os.path.isfile(path):
        return []
    with open(path, "r", encoding="utf-8") as f:
        lines = [ln.rstrip("\n") for ln in f]
    entries = []
    for ln in lines:
        ln = ln.strip()
        if not ln or " _ " not in ln:
            continue
        left, _, right = ln.partition(" _ ")
        origin_src = left.strip().strip('"').strip("'").strip()
        dialect = normalize_line(right.strip().strip('"').strip("'").strip())
        if origin_src and dialect:
            entries.append((origin_src, dialect))
    return entries


def _parse_origin_mappings(path):
    """Parse origin.toml into {normalized_dialect_line: origin_source} (exact only)."""
    out = {}
    for origin_src, dialect in _parse_origin_toml(path):
        if "$" in dialect:
            continue
        out[dialect] = origin_src
    return out


def origin_mappings(path=None):
    """Return (and cache) {dialect_line: origin_source} from origin.toml."""
    global _ORIGIN_MAP, _ORIGIN_MAP_PATH
    path = path or _default_path("origin.toml")
    if _ORIGIN_MAP is not None and _ORIGIN_MAP_PATH == path:
        return _ORIGIN_MAP
    _ORIGIN_MAP = _parse_origin_mappings(path)
    _ORIGIN_MAP_PATH = path
    return _ORIGIN_MAP


def _template_regex(template):
    """Compile a dialect template to (regex, names); None regex if malformed."""
    parts = []
    names = []
    pos = 0
    for m in _TEMPLATE_TOKEN.finditer(template):
        if m.start() > pos:
            parts.append(re.escape(template[pos:m.start()]))
        if m.group(0) == "$$":
            parts.append(re.escape("$"))
        else:
            name = m.group(1)
            if name in names:
                parts.append(f"(?P={name})")  # repeated placeholder: must match
            else:
                names.append(name)
                parts.append(f"(?P<{name}>.+?)")
        pos = m.end()
    if pos < len(template):
        parts.append(re.escape(template[pos:]))
    try:
        return re.compile("".join(parts)), names
    except re.error:
        return None, []


def _substitute(template, captures):
    """Replace ``$name`` in an origin template with captured text."""
    out = []
    pos = 0
    for m in _TEMPLATE_TOKEN.finditer(template):
        out.append(template[pos:m.start()])
        if m.group(0) == "$$":
            out.append("$")
        else:
            out.append(captures.get(m.group(1), ""))
        pos = m.end()
    out.append(template[pos:])
    return "".join(out)


def _parse_origin_patterns(path):
    """Compile templated mappings into [(regex, origin_template, names)]."""
    patterns = []
    for origin_tpl, dialect_tpl in _parse_origin_toml(path):
        if "$" not in dialect_tpl:
            continue
        regex, names = _template_regex(dialect_tpl)
        if regex is None:
            continue
        if not set(_PLACEHOLDER.findall(origin_tpl)) <= set(names):
            continue
        patterns.append((regex, origin_tpl, names))
    return patterns


def origin_patterns(path=None):
    """Return (and cache) compiled template patterns, in file order."""
    global _PATTERNS, _PATTERNS_PATH
    path = path or _default_path("origin.toml")
    if _PATTERNS is not None and _PATTERNS_PATH == path:
        return _PATTERNS
    _PATTERNS = _parse_origin_patterns(path)
    _PATTERNS_PATH = path
    return _PATTERNS


def lookup_origin(line, path=None):
    """Map a dialect source line to its origin source, or None.

    Exact mappings win; otherwise templates are tried in file order.
    """
    if not _ENABLED:
        return None
    norm = normalize_line(line)
    exact = origin_mappings(path).get(norm)
    if exact is not None:
        return exact
    for regex, origin_tpl, _names in origin_patterns(path):
        m = regex.fullmatch(norm)
        if m:
            return _substitute(origin_tpl, m.groupdict())
    return None


def _parse_file(path):
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    if not text.strip():
        return {}
    # 1) real TOML (stdlib, 3.11+)
    try:
        import tomllib
        data = tomllib.loads(text)
        if isinstance(data, dict):
            return data
    except Exception:
        pass
    # 2) historical runnerTOML format: str(dict)
    try:
        data = ast.literal_eval(text)
        if isinstance(data, dict):
            return data
    except Exception:
        pass
    return {}


def _coerce_entry(value):
    """Return (bytecode, constants) or None for a raw legacy table value."""
    if isinstance(value, dict):
        code = value.get("bytecode", [])
        consts = value.get("constants", [])
        if isinstance(code, (list, tuple)) and isinstance(consts, (list, tuple)):
            return list(code), list(consts)
        return None
    if isinstance(value, (list, tuple)):
        return list(value), []
    return None


def load_table(path=None):
    """Load (and cache) the legacy dialect bytecode table."""
    global _TABLE, _TABLE_PATH
    path = path or _default_path("origin_bytecode.toml")
    if _TABLE is not None and _TABLE_PATH == path:
        return _TABLE
    table = {}
    if os.path.isfile(path):
        for key, value in _parse_file(path).items():
            entry = _coerce_entry(value)
            if entry is not None:
                table[normalize_line(str(key))] = entry
    _TABLE = table
    _TABLE_PATH = path
    return table


def lookup_dialect(line, path=None):
    """Look up a legacy precompiled line. Returns (bytecode, constants) or None."""
    if not _ENABLED:
        return None
    table = load_table(path)
    if not table:
        return None
    return table.get(normalize_line(line))


def reset_table():
    """Clear cached tables (mainly for tests)."""
    global _TABLE, _TABLE_PATH, _ORIGIN_MAP, _ORIGIN_MAP_PATH
    global _PATTERNS, _PATTERNS_PATH, _ENABLED
    _TABLE = None
    _TABLE_PATH = None
    _ORIGIN_MAP = None
    _ORIGIN_MAP_PATH = None
    _PATTERNS = None
    _PATTERNS_PATH = None
    _ENABLED = True
